import { test, expect } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const captures = path.resolve('../evidencias/capturas')
const proofs = path.resolve('../evidencias/pruebas')
mkdirSync(captures, { recursive: true })
mkdirSync(proofs, { recursive: true })
const shot = async (page: import('@playwright/test').Page, name: string) => {
  await page.locator('.toast').waitFor({ state: 'hidden', timeout: 5000 })
  await page.screenshot({ path: path.join(captures, name), fullPage: true, animations: 'disabled' })
}
const mobileNav = (page: import('@playwright/test').Page, name: string) => page.locator('.mobile-nav').getByRole('button', { name })

test('flujo funcional, persistencia, exportación y capturas reales', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, locale: 'es-PE', acceptDownloads: true })
  const page = await context.newPage()
  const results: string[] = []
  await page.goto('/')
  await expect(page.getByText('Empieza a organizar tu dinero')).toBeVisible()
  await shot(page, '01_inicio.png')
  results.push('Inicio vacío: correcto')

  await page.locator('.add-button').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await shot(page, '03_registro.png')
  await page.getByRole('button', { name: 'Ingreso', exact: true }).click()
  await page.getByLabel('Monto').fill('0')
  await page.getByLabel('Descripción').fill('Registro inválido')
  await page.getByRole('dialog').getByRole('button', { name: 'Agregar movimiento' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByLabel('Monto').fill('500')
  await page.getByLabel('Categoría', { exact: true }).selectOption('Beca')
  await page.getByLabel('Descripción').fill('Beca de prueba')
  await page.getByRole('dialog').getByRole('button', { name: 'Agregar movimiento' }).click()
  await expect(page.getByText('Beca de prueba')).toBeVisible()
  await expect(page.getByText('S/ 500.00').first()).toBeVisible()
  results.push('Registro de ingreso y actualización de estadísticas: correcto')
  results.push('Validación de monto cero: correcto')

  await page.locator('.add-button').click()
  await page.getByLabel('Monto').fill('35')
  await page.getByLabel('Descripción').fill('Almuerzo de prueba')
  await page.getByRole('dialog').getByRole('button', { name: 'Agregar movimiento' }).click()
  await expect(page.getByText('Almuerzo de prueba')).toBeVisible()
  results.push('Registro de gasto: correcto')

  await mobileNav(page, 'Movimientos').click()
  await page.getByRole('button', { name: 'Editar Almuerzo de prueba' }).click()
  await page.getByLabel('Monto').fill('40')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByText('S/ 40.00').first()).toBeVisible()
  results.push('Edición de gasto: correcto')

  await page.getByLabel('Filtrar por tipo').selectOption('ingreso')
  await expect(page.getByText('Beca de prueba')).toBeVisible()
  await expect(page.getByText('Almuerzo de prueba')).toHaveCount(0)
  await page.getByLabel('Filtrar por tipo').selectOption('todos')
  await page.getByLabel('Filtrar por categoría').selectOption('Alimentación')
  await expect(page.getByText('Almuerzo de prueba')).toBeVisible()
  await expect(page.getByText('Beca de prueba')).toHaveCount(0)
  await page.getByLabel('Filtrar por categoría').selectOption('todas')
  await page.getByLabel('Filtrar desde').fill('2099-01-01')
  await expect(page.getByText('No hay movimientos para mostrar')).toBeVisible()
  await page.getByLabel('Filtrar desde').fill('')
  results.push('Filtros por tipo, categoría y fecha: correcto')

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar CSV' }).click()
  const download = await downloadPromise
  const filePath = path.join(proofs, download.suggestedFilename())
  await download.saveAs(filePath)
  const csv = await import('node:fs').then(fs => fs.readFileSync(filePath, 'utf8'))
  expect(csv).toContain('Beca de prueba')
  expect(csv).toContain('Almuerzo de prueba')
  results.push('Exportación CSV y contenido: correcto')

  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Eliminar Almuerzo de prueba' }).click()
  await expect(page.getByText('Almuerzo de prueba')).toHaveCount(0)
  results.push('Eliminación: correcto')

  await page.reload()
  await mobileNav(page, 'Movimientos').click()
  await expect(page.getByText('Beca de prueba')).toBeVisible()
  results.push('Persistencia tras recarga: correcto')

  await mobileNav(page, 'Presupuesto').click()
  await page.getByLabel('Presupuesto mensual').fill('650')
  await page.getByLabel('Próximo ingreso').fill('2099-01-01')
  await page.getByLabel('Límite Ocio').fill('35')
  await page.getByRole('button', { name: 'Guardar presupuesto' }).click()
  await expect(page.getByText('Presupuesto guardado')).toBeVisible()
  await page.reload()
  await mobileNav(page, 'Presupuesto').click()
  await expect(page.getByLabel('Presupuesto mensual')).toHaveValue('650')
  await expect(page.getByLabel('Límite Ocio')).toHaveValue('35')
  results.push('Configuración de presupuesto y límites persistente: correcto')

  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Cargar datos de demostración' }).click()
  await expect(page.getByText('Límite excedido: Ocio.')).toBeVisible()
  await shot(page, '02_dashboard.png')
  await mobileNav(page, 'Movimientos').click()
  await shot(page, '04_movimientos.png')
  await mobileNav(page, 'Presupuesto').click()
  await shot(page, '05_presupuesto.png')
  await expect(page.getByText('Límite superado')).toBeVisible()
  await mobileNav(page, 'Estadísticas').click()
  await shot(page, '06_graficos.png')
  await page.reload()
  await expect(page.getByText('Apoyo mensual')).toHaveCount(0)
  await mobileNav(page, 'Movimientos').click()
  await expect(page.getByText('Apoyo mensual')).toBeVisible()
  await shot(page, '07_persistencia.png')
  const mobileWidth = await page.evaluate(() => document.documentElement.scrollWidth)
  expect(mobileWidth).toBeLessThanOrEqual(390)
  results.push('Datos de ejemplo, alertas, gráficos y vista móvil sin desborde: correcto')

  const desktop = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, locale: 'es-PE' })
  const dpage = await desktop.newPage()
  await dpage.goto('/')
  await expect(dpage.getByText('Empieza a organizar tu dinero')).toBeVisible()
  await dpage.getByRole('button', { name: 'Cargar datos de demostración' }).click()
  await expect(dpage.getByText('Límite excedido: Ocio.')).toBeVisible()
  await shot(dpage, '08_responsive.png')
  expect(await dpage.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1440)
  results.push('Vista de escritorio 1440 × 900 sin desborde: correcto')
  writeFileSync(path.join(proofs, 'resultados-funcionales.txt'), results.join('\n') + '\n', 'utf8')
  await context.close()
  await desktop.close()
})
