import { test, expect } from '@playwright/test'
import path from 'node:path'

test('capturas de detalle para el informe', async ({ browser }) => {
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, locale: 'es-PE' })
  const page = await mobile.newPage()
  const out = path.resolve('../evidencias/capturas')
  await page.goto('/')
  await page.getByRole('button', { name: 'Cargar datos de demostración' }).click()
  await expect(page.getByText('Límite excedido: Ocio.')).toBeVisible()
  await page.locator('.toast').waitFor({ state: 'hidden' })
  await page.screenshot({ path: path.join(out, '09_panel_lectura.png'), animations: 'disabled' })
  await page.mouse.move(0, 0)
  await page.locator('.chart-card').evaluate(el => el.scrollIntoView({ block: 'start' }))
  await page.locator('.chart-card').screenshot({ path: path.join(out, '10_distribucion_detalle.png'), animations: 'disabled' })
  await page.locator('.mobile-nav').getByRole('button', { name: 'Presupuesto' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: path.join(out, '13_presupuesto_formulario.png'), animations: 'disabled' })
  await page.locator('.progress-card').evaluate(el => el.scrollIntoView({ block: 'start' }))
  await page.locator('.progress-card').screenshot({ path: path.join(out, '11_consumo_detalle.png'), animations: 'disabled' })
  await page.locator('.mobile-nav').getByRole('button', { name: 'Estadísticas' }).click()
  await page.locator('.stats-grid .card').first().evaluate(el => el.scrollIntoView({ block: 'start' }))
  await page.locator('.stats-grid .card').first().screenshot({ path: path.join(out, '12_evolucion_detalle.png'), animations: 'disabled' })
  await page.locator('.mobile-nav').getByRole('button', { name: 'Movimientos' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: path.join(out, '14_historial_lectura.png'), animations: 'disabled' })
  await page.reload()
  await page.locator('.mobile-nav').getByRole('button', { name: 'Movimientos' }).click()
  await expect(page.getByText('Apoyo mensual')).toBeVisible()
  await page.getByText('Apoyo mensual').evaluate(el => el.scrollIntoView({ block: 'center' }))
  await page.waitForTimeout(200)
  await page.screenshot({ path: path.join(out, '15_persistencia_lectura.png'), animations: 'disabled' })
  await mobile.close()
})
