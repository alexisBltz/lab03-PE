import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
import path from 'node:path'

test('recorrido demostrativo grabado', async ({ browser }) => {
  const videoDir = path.resolve('../video')
  mkdirSync(videoDir, { recursive: true })
  const context = await browser.newContext({
    viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, locale: 'es-PE',
    recordVideo: { dir: videoDir, size: { width: 390, height: 844 } },
  })
  const page = await context.newPage()
  const nav = (name: string) => page.locator('.mobile-nav').getByRole('button', { name })
  await page.goto('/')
  await expect(page.getByText('Empieza a organizar tu dinero')).toBeVisible()
  await page.waitForTimeout(1200)
  await page.locator('.add-button').click()
  await page.getByRole('button', { name: 'Ingreso', exact: true }).click()
  await page.getByLabel('Monto').fill('500')
  await page.getByLabel('Descripción').fill('Beca de ejemplo')
  await page.waitForTimeout(800)
  await page.getByRole('dialog').getByRole('button', { name: 'Agregar movimiento' }).click()
  await page.waitForTimeout(1200)
  await page.locator('.add-button').click()
  await page.getByLabel('Monto').fill('35')
  await page.getByLabel('Descripción').fill('Almuerzo universitario')
  await page.waitForTimeout(800)
  await page.getByRole('dialog').getByRole('button', { name: 'Agregar movimiento' }).click()
  await page.waitForTimeout(1200)
  await nav('Movimientos').click()
  await page.waitForTimeout(1400)
  await nav('Presupuesto').click()
  await page.getByLabel('Presupuesto mensual').fill('650')
  await page.getByLabel('Próximo ingreso').fill(new Date(Date.now() + 14 * 86400000).toISOString().slice(0, 10))
  await page.getByLabel('Límite Alimentación').fill('120')
  await page.getByRole('button', { name: 'Guardar presupuesto' }).click()
  await page.waitForTimeout(1300)
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Cargar datos de demostración' }).click()
  await expect(page.getByText('Límite excedido: Ocio.')).toBeVisible()
  await page.waitForTimeout(3800)
  await nav('Estadísticas').click()
  await page.waitForTimeout(1700)
  await page.reload()
  await nav('Movimientos').click()
  await expect(page.getByText('Apoyo mensual')).toBeVisible()
  await page.waitForTimeout(1700)
  const video = page.video()
  await context.close()
  await video?.saveAs(path.join(videoDir, 'demostracion.webm'))
})
